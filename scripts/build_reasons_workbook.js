// 1. Build JSON file for instant, rock-solid server-side / client-side import & fallback
const dataDir = path.join(__dirname, "..", "data");
if (!fs.existsSync(dataDir)) fs.mkdirSync(dataDir, { recursive: true });

const reasonsJson = REASONS_RAW.map(([day, reason]) => ({
  day,
  reason,
  display_date_relative: `Day ${day}`,
  status: "Ready to display"
}));

fs.writeFileSync(
  path.join(dataDir, "Our_Little_Universe_365_Reasons.json"),
  JSON.stringify(reasonsJson, null, 2),
  "utf8"
);

// 2. Build Excel Workbook data/Our_Little_Universe_365_Reasons.xlsx
